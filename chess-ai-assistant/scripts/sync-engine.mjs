#!/usr/bin/env node
/**
 * Copies the Stockfish WebAssembly build from the npm package into public/engine
 * so that Vite ships it verbatim, and writes a provenance manifest.
 *
 * Usage:
 *   node scripts/sync-engine.mjs                    # lite-single (default, GitHub Pages safe)
 *   node scripts/sync-engine.mjs --flavor=full-single
 *   node scripts/sync-engine.mjs --flavor=lite     # multithreaded, needs COOP/COEP headers
 */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgRoot = join(root, 'node_modules', 'stockfish');
const pkgJson = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8'));
const VERSION = pkgJson.version; // e.g. 19.0.1
const BUILD = pkgJson.buildVersion ?? VERSION.split('.')[0]; // e.g. 19

const flavorArg = process.argv.find((a) => a.startsWith('--flavor='));
const flavor = flavorArg ? flavorArg.split('=')[1] : 'lite-single';
const supported = ['lite-single', 'lite', 'single', 'full', 'asm'];
if (!supported.includes(flavor)) {
  console.error(`Unknown flavor "${flavor}". Choose one of: ${supported.join(', ')}`);
  process.exit(1);
}

const binDir = join(pkgRoot, 'bin');
const outDir = join(root, 'public', 'engine');
mkdirSync(outDir, { recursive: true });

const isAsm = flavor === 'asm';
const baseName = `stockfish-${BUILD}${flavor === 'full' ? '' : '-' + flavor}`;
const files = isAsm ? [`${baseName}.js`] : [`${baseName}.js`, `${baseName}.wasm`];

if (!existsSync(join(binDir, files[0]))) {
  console.error(`Engine file not found: ${join(binDir, files[0])}`);
  console.error('Run `npm install` first.');
  process.exit(1);
}

const manifest = [
  'Stockfish WebAssembly build distributed with Chess AI Arena',
  '=========================================================',
  `npm package : stockfish@${VERSION} (nmrugg/stockfish.js)`,
  `flavor      : ${flavor}`,
  `build tag   : v${VERSION}`,
  '',
  'Upstream projects',
  '-----------------',
  'Stockfish engine        : https://github.com/official-stockfish/Stockfish',
  'Stockfish.js WASM build : https://github.com/nmrugg/stockfish.js',
  '',
  'License: GNU General Public License version 3 (see LICENSE-stockfish.txt).',
  'The engine files below are unmodified copies from the npm package.',
  '',
  'Files and SHA-256 checksums',
  '---------------------------',
];

for (const f of files) {
  copyFileSync(join(binDir, f), join(outDir, f));
  const hash = createHash('sha256').update(readFileSync(join(binDir, f))).digest('hex');
  manifest.push(`${hash}  ${f}`);
  console.log(`copied ${f} (${(readFileSync(join(binDir, f)).length / 1e6).toFixed(2)} MB)`);
}

copyFileSync(join(pkgRoot, 'Copying.txt'), join(outDir, 'LICENSE-stockfish.txt'));
copyFileSync(join(pkgRoot, 'README.md'), join(outDir, 'README-stockfish-js.md'));

// Teach the app which engine file to boot, without hardcoding it in the bundle.
const engineConfig = `// Generated by scripts/sync-engine.mjs — do not edit by hand.\n` +
  `export const ENGINE_FILES: string[] = ${JSON.stringify(files)};\n`;
writeFileSync(join(root, 'src', 'engine', 'engineFiles.ts'), engineConfig);

writeFileSync(join(outDir, 'ENGINE-MANIFEST.txt'), manifest.join('\n') + '\n');
console.log(`engine flavor: ${flavor} -> public/engine/`);
